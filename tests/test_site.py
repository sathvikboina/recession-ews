"""tests/test_site.py

Fast (< 5s) test suite verifying the offline static site generated by scripts/09_build_site.py:
1. All six pages exist (index.html, labels.html, features.html, folds.html, baselines.html, countries.html).
2. Every internal href in navigation/links resolves to a local file in site/.
3. No external http:// or https:// URLs in src/href/url (strictly offline, file:// compliant).
4. Each page has >= 1 interactive control (<input>, <select>, or <button>) and a <script> block.
5. Embedded JSON block parses cleanly and the frozen label hash in index.html equals 2379fd53e4c9023538cafcd5668a4835bcdd7b45cfae9e3cbc3d4f306ed19daa.
6. Determinism: regenerating twice produces byte-identical files.
"""
from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path
import pytest
import importlib

PROJECT = Path(__file__).resolve().parents[1]
SITE_DIR = PROJECT / "site"

EXPECTED_PAGES = [
    "index.html",
    "labels.html",
    "features.html",
    "folds.html",
    "baselines.html",
    "countries.html",
]
EXPECTED_LABEL_HASH = "2379fd53e4c9023538cafcd5668a4835bcdd7b45cfae9e3cbc3d4f306ed19daa"


@pytest.fixture(scope="module")
def site_pages():
    pages = {}
    for name in EXPECTED_PAGES:
        p = SITE_DIR / name
        assert p.exists(), f"Missing required site page: {p}"
        pages[name] = p.read_text(encoding="utf-8")
    return pages


def test_pages_exist_and_internal_hrefs_resolve(site_pages):
    """Test 1: All 6 pages exist and every internal href points to a valid file in site/."""
    for name, content in site_pages.items():
        hrefs = re.findall(r'href=["\']([^"\']+)["\']', content)
        for h in hrefs:
            if h.startswith("#") or h.startswith("mailto:"):
                continue
            target = SITE_DIR / h.split("#")[0]
            assert target.exists(), f"Broken internal link '{h}' in {name}"


def test_no_external_urls(site_pages):
    """Test 2: Zero http:// or https:// in any page (strictly offline)."""
    for name, content in site_pages.items():
        assert "http://" not in content, f"External http:// found in {name}"
        assert "https://" not in content, f"External https:// found in {name}"


def test_controls_and_scripts_present(site_pages):
    """Test 3: Each page has >= 1 input/select/button and a <script> block."""
    for name, content in site_pages.items():
        has_input = "<input" in content
        has_select = "<select" in content
        has_button = "<button" in content
        assert has_input or has_select or has_button, f"No interactive control found in {name}"

        assert "<script" in content and "</script>" in content, f"No script block found in {name}"
        assert '<script type="application/json"' in content, f"Missing embedded JSON script block in {name}"


def test_embedded_json_and_label_hash(site_pages):
    """Test 4: Embedded JSON parses and index.html contains the exact frozen label hash."""
    index_html = site_pages["index.html"]
    assert EXPECTED_LABEL_HASH in index_html, f"Label hash {EXPECTED_LABEL_HASH} missing in index.html"

    for name, content in site_pages.items():
        match = re.search(r'<script type="application/json"[^>]*>(.*?)</script>', content, re.DOTALL)
        assert match, f"Could not find JSON block in {name}"
        data = json.loads(match.group(1))
        assert isinstance(data, dict), f"Embedded JSON in {name} is not a valid dict"
        if name == "index.html":
            assert data.get("label_hash") == EXPECTED_LABEL_HASH, f"Hash mismatch in JSON of {name}"


def test_determinism():
    """Test 5: Regenerating twice produces byte-identical files matching disk."""
    sys.path.insert(0, str(PROJECT / "scripts"))
    mod = importlib.import_module("09_build_site")

    d1 = mod.extract_data()
    pages1 = {
        "index.html": mod.build_index(d1).replace("\r\n", "\n").encode("utf-8"),
        "labels.html": mod.build_labels(d1).replace("\r\n", "\n").encode("utf-8"),
        "features.html": mod.build_features(d1).replace("\r\n", "\n").encode("utf-8"),
        "folds.html": mod.build_folds(d1).replace("\r\n", "\n").encode("utf-8"),
        "baselines.html": mod.build_baselines(d1).replace("\r\n", "\n").encode("utf-8"),
        "countries.html": mod.build_countries(d1).replace("\r\n", "\n").encode("utf-8"),
    }
    hashes1 = {name: hashlib.sha256(pages1[name]).hexdigest() for name in EXPECTED_PAGES}

    d2 = mod.extract_data()
    pages2 = {
        "index.html": mod.build_index(d2).replace("\r\n", "\n").encode("utf-8"),
        "labels.html": mod.build_labels(d2).replace("\r\n", "\n").encode("utf-8"),
        "features.html": mod.build_features(d2).replace("\r\n", "\n").encode("utf-8"),
        "folds.html": mod.build_folds(d2).replace("\r\n", "\n").encode("utf-8"),
        "baselines.html": mod.build_baselines(d2).replace("\r\n", "\n").encode("utf-8"),
        "countries.html": mod.build_countries(d2).replace("\r\n", "\n").encode("utf-8"),
    }
    hashes2 = {name: hashlib.sha256(pages2[name]).hexdigest() for name in EXPECTED_PAGES}

    for name in EXPECTED_PAGES:
        assert hashes1[name] == hashes2[name], f"Non-deterministic for {name}"
        disk_bytes = (SITE_DIR / name).read_bytes().replace(b"\r\n", b"\n")
        disk_hash = hashlib.sha256(disk_bytes).hexdigest()
        assert disk_hash == hashes1[name], f"Disk out of sync for {name}: {disk_hash} != {hashes1[name]}"
